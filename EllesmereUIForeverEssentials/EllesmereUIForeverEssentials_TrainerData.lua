local talentOf = {}

local function Talent(class, spellID)
    local by = talentOf[class]
    if not by then
        by = {}
        for _, family in ipairs(TALENTS[class] or {}) do
            for _, id in ipairs(family) do by[id] = family end
        end
        talentOf[class] = by
    end
    return by[spellID]
end

-- module.SpellIsTalent(class, spellID): a talent's own spell or a higher rank.
function module.SpellIsTalent(class, spellID)
    return Talent(class, spellID) ~= nil
end

-- module.TalentRankOpen(class, spellID): for the player's own class, a higher
-- rank of a talent the player has (any rank of it is known).
function module.TalentRankOpen(class, spellID)
    local family = Talent(class, spellID)
    if not family or family[1] == spellID then return false end
    for i = 1, #family do
        if IsPlayerSpell(family[i]) then return true end
    end
    return false
end


local data, byClass, byClassAll, racial = nil, {}, {}, {}

function module.TrainerSpells(class, allRaces)
    local cache = allRaces and byClassAll or byClass
    local out = cache[class]
    if out then return out end
    data = data or Data()
    out = {}
    local masks = racial[class] or {}
    racial[class] = masks
    local race = bit.lshift(1, select(3, UnitRace("player")) - 1)
    for level, list in pairs(data[class] or {}) do
        local spells = {}
        for i = 1, #list do
            local e = list[i]
            if type(e) == "number" then
                spells[#spells + 1] = e
            else
                masks[e[1]] = e[2]
                if allRaces or bit.band(e[2], race) ~= 0 then
                    spells[#spells + 1] = e[1]
                end
            end
        end
        out[level] = spells
    end
    cache[class] = out
    return out
end

function module.SpellRaces(class, spellID)
    return racial[class] and racial[class][spellID]
end

