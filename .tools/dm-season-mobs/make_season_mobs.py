"""Regenerates EllesmereUIDamageMeters/EUI_DamageMeters_SeasonMobs.lua: the NPC
IDs of every enemy (bosses included) in each dungeon of the current Mythic+
season, keyed by the dungeon's Mythic+ map ID. Damage Meters matches a hovered
Enemy Damage Taken row against these mid-fight.

The source is the dungeon data of Mythic Dungeon Tools (GPL-2.0; its author is
fine with this use). Its newest season is the first list in
Modules/DungeonSelect.lua; each dungeon file names its index, its Mythic+ map
ID (mapInfo.mapID) and its enemies (the 4-space "id" lines of dungeonEnemies).

Usage:  python .tools/dm-season-mobs/make_season_mobs.py <path to the MythicDungeonTools folder>
Run it again when a new season's dungeon list ships.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "EllesmereUIDamageMeters", "EUI_DamageMeters_SeasonMobs.lua")


def read(path):
    with open(path, "r", encoding="utf-8", errors="strict") as f:
        return f.read()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    select = read(os.path.join(src, "Modules", "DungeonSelect.lua"))
    season = re.search(r'tinsert\(MDT\.seasonList,\s*L\["([^"]+)"\]\)', select)
    first = re.search(r'tinsert\(MDT\.dungeonSelectionToIndex,\s*\{([^}]*)\}\)', select)
    if not season or not first:
        sys.exit("could not find the newest season list in DungeonSelect.lua")
    wanted = [int(x) for x in re.findall(r"\d+", first.group(1))]

    found = {}
    for dirpath, _, files in os.walk(src):
        for name in files:
            if not name.endswith(".lua"):
                continue
            text = read(os.path.join(dirpath, name))
            m = re.search(r"^local dungeonIndex = (\d+)", text, re.M)
            if not m or int(m.group(1)) not in wanted:
                continue
            idx = int(m.group(1))
            info = re.search(r"MDT\.mapInfo\[dungeonIndex\] = \{(.*?)\n\}", text, re.S)
            map_id = info and re.search(r"mapID = (\d+)", info.group(1))
            english = info and re.search(r'englishName = "([^"]+)"', info.group(1))
            enemies_at = text.find("MDT.dungeonEnemies[dungeonIndex]")
            if not map_id or enemies_at < 0:
                sys.exit("%s: no mapID or no enemy table" % name)
            ids = sorted({int(x) for x in re.findall(r'^    \["id"\] = (\d+),', text[enemies_at:], re.M)})
            if not ids:
                sys.exit("%s: no enemy IDs" % name)
            found[idx] = (int(map_id.group(1)), english.group(1) if english else name[:-4], ids)

    missing = [i for i in wanted if i not in found]
    if missing:
        sys.exit("dungeon files not found for indexes %s" % missing)

    lines = [
        "if EUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (EllesmereUI_ClientGate.lua)",
        "if EllesmereUI and EllesmereUI.IS_FOREVER then return end",
        "-- Generated by .tools/dm-season-mobs/make_season_mobs.py (%s); do not edit by hand." % season.group(1),
        "-- Credit to Nnoggie (Mythic Dungeon Tools) for the dungeon enemy data, used with permission.",
        "-- SEASON UPDATE: rerun the generator once Mythic Dungeon Tools lists the new season's dungeons.",
        "-- Mythic+ map ID = { the NPC ID of every enemy in that dungeon, bosses included }",
        "local _, ns = ...",
        "ns.DM_SEASON_MOBS = {",
    ]
    for idx in wanted:
        map_id, english, ids = found[idx]
        lines.append("[%d] = { %s }, -- %s" % (map_id, ", ".join(str(i) for i in ids), english))
    lines.append("}")
    body = "\r\n".join(lines) + "\r\n"
    body.encode("ascii")  # raises on a non-ASCII dungeon name
    with open(OUT, "w", encoding="ascii", newline="") as f:
        f.write(body)
    print("wrote %s: %d dungeons, %d NPC IDs (%s)" % (
        os.path.relpath(OUT, ROOT), len(wanted), sum(len(found[i][2]) for i in wanted), season.group(1)))


if __name__ == "__main__":
    main()
