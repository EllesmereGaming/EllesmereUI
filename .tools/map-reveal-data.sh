#!/usr/bin/env bash
#
# map-reveal-data.sh
# Regenerates the world map overlay data of Forever Essentials' Reveal
# Unexplored Areas (EllesmereUIForeverEssentials_MapRevealData.lua) from the
# WorldMapOverlay tables of a WoW Forever build on wago.tools.
#
# Usage:  ./.tools/map-reveal-data.sh <forever build>
#   e.g.  ./.tools/map-reveal-data.sh 1.60.1.70338
# Needs curl and GNU awk.
#
set -euo pipefail
export LC_ALL=C

[ $# -eq 1 ] || { echo "usage: $0 <forever build>" >&2; exit 1; }
cd "$(dirname "$0")/.."

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
TABLES="UiMapArtStyleLayer UiMapArt UiMapXMapArt WorldMapOverlay WorldMapOverlayTile"

fetch() {
  for t in $TABLES; do
    curl -fsSL -A "EllesmereUI-tools" "https://wago.tools/db2/$t/csv?build=$1" -o "$TMP/$t.csv"
  done
}

# Overlays shown on mouseover only, behind a player condition, without size or
# on an art no map uses are left out, so are exact duplicates.
build() {
  local build="$1" out="$2"
  fetch "$build"
  {
    echo "if EUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (EllesmereUI_ClientGate.lua)"
    echo "if not (EllesmereUI and EllesmereUI.IS_FOREVER) then return end"
    echo "-- Generated by .tools/map-reveal-data.sh from build $build."
    echo "-- uiMapArtID = { { width, height, offsetX, offsetY, tile fileDataIDs row by row }, ... }"
    echo "local _, ns = ..."
    echo "ns.MapRevealData = {"
    (cd "$TMP" && gawk -F, '
      FNR == 1 { file++; delete col; for (i = 1; i <= NF; i++) col[$i] = i; next }
      function f(name) {
        if (!(name in col)) { printf "%s: no column %s\n", FILENAME, name > "/dev/stderr"; err = 1; exit 1 }
        return $(col[name])
      }
      file == 1 { if (f("LayerIndex") == 0) { tw[f("UiMapArtStyleID")] = f("TileWidth"); th[f("UiMapArtStyleID")] = f("TileHeight") } next }
      file == 2 { style[f("ID")] = f("UiMapArtStyleID"); next }
      file == 3 { used[f("UiMapArtID")] = 1; next }
      file == 4 {
        id = f("ID")
        if (!(f("UiMapArtID") in used) || f("PlayerConditionID") != 0 || and(f("Flags"), 1) || f("TextureWidth") == 0 || f("TextureHeight") == 0) next
        keep[id] = 1; art[id] = f("UiMapArtID")
        w[id] = f("TextureWidth"); h[id] = f("TextureHeight"); x[id] = f("OffsetX"); y[id] = f("OffsetY")
        next
      }
      file == 5 {
        id = f("WorldMapOverlayID"); r = f("RowIndex"); c = f("ColIndex")
        if (!(id in keep) || f("LayerIndex") != 0) next
        tile[id "," r "," c] = f("FileDataID")
        if (r + 1 > rows[id]) rows[id] = r + 1
        if (c + 1 > cols[id]) cols[id] = c + 1
      }
      END {
        if (err) exit 1
        PROCINFO["sorted_in"] = "@ind_num_asc"
        for (id in keep) {
          a = art[id]; s = style[a]
          nc = int((w[id] + tw[s] - 1) / tw[s]); nr = int((h[id] + th[s] - 1) / th[s])
          if (nc != cols[id] || nr != rows[id]) { bad++; continue }
          line = w[id] "," h[id] "," x[id] "," y[id]
          miss = 0
          for (r = 0; r < nr; r++) for (c = 0; c < nc; c++) {
            k = id "," r "," c
            if (!(k in tile)) miss = 1
            line = line "," tile[k]
          }
          if (miss) { bad++; continue }
          if ((a, line) in seen) continue
          seen[a, line] = 1
          out[a] = out[a] (out[a] == "" ? "" : ", ") "{" line "}"
        }
        for (a in out) printf "[%d] = { %s },\n", a, out[a]
        if (bad) printf "%d overlays skipped (tiles missing or not matching the size)\n", bad > "/dev/stderr"
      }' UiMapArtStyleLayer.csv UiMapArt.csv UiMapXMapArt.csv WorldMapOverlay.csv WorldMapOverlayTile.csv)
    echo "}"
  } > "$TMP/out.lua"
  mv "$TMP/out.lua" "$out"
  echo "Wrote $out"
}

build "$1" EllesmereUIForeverEssentials/EllesmereUIForeverEssentials_MapRevealData.lua
